function getProfessionEntry(professionKey) {
  const k = String(professionKey || "").trim().toUpperCase();
  return QUEBEC_APICES_REGISTRY[k] || null;
}

function listSoloProfessionsPublic() {
  return QUEBEC_SOLO_PROFESSIONS.map((p) => ({
    key: p.key,
    sectorId: p.sectorId,
    regulatoryBody: p.regulatoryBody,
    defaultMaterialityCad: p.defaultMaterialityCad,
    engineRuleSummary: p.engineRuleSummary,
    title: p.title,
    labels: p.labels,
  }));
}

function resolveProfessionSetupDefaults({ scaleType, professionKey, sectorId }) {
  const isSolo = String(scaleType || "").toUpperCase() === "AUTONOMOUS_SOLO";
  const prof = getProfessionEntry(professionKey);
  if (prof) {
    return {
      professionKey: prof.key,
      sectorId: sectorId || prof.sectorId || "solo",
      defaultMaterialityCad: prof.defaultMaterialityCad,
      regulatoryBody: prof.regulatoryBody,
    };
  }
  return {
    professionKey: isSolo ? "AUTRE_AUTONOME" : "",
    sectorId: sectorId || (isSolo ? "solo" : "generic"),
    defaultMaterialityCad: isSolo ? 250 : 500,
    regulatoryBody: "",
  };
}

